# install_hook <repo-worktree> <hook-name> <body>
install_hook() {
  repo=$1
  name=$2
  body=$3

  # rev-parse --git-path resolves .git-as-a-file (worktrees, submodules) too.
  hooks=$(git -C "$repo" rev-parse --git-path hooks 2>/dev/null) || {
    echo "skipped $repo — not a git repository" >&2
    return 0
  }
  case "$hooks" in /*) ;; *) hooks="$repo/$hooks" ;; esac
  mkdir -p "$hooks"
  hook="$hooks/$name"

  # This header has claimed idempotence since day one while `cat >` overwrote unconditionally,
  # so installing into a repo that already had its own pre-commit (husky, lefthook, a
  # hand-rolled linter) destroyed it silently. Only replace hooks this script generated.
  if [ -e "$hook" ] && ! grep -qF "$MARKER" "$hook" 2>/dev/null; then
    echo "skipped $hook — existing hook was not generated by this script; leaving it alone" >&2
    echo "        move or delete it and re-run to install the shared gate." >&2
    return 0
  fi

  # Both sides through command substitution so the trailing-newline handling matches.
  if [ -e "$hook" ] && [ "$(cat "$hook")" = "$(printf '%s' "$body")" ]; then
    echo "up to date $hook"
    return 0
  fi

  printf '%s' "$body" > "$hook"
  chmod +x "$hook"
  echo "installed  $hook"
}

install_hook "$root" pre-commit "$root_body"
install_hook "$root" pre-push   "$push_body"

# A root-repo worktree has no projects/ at all — the nested repos live only in the primary
# checkout. Hard-failing here would red out every worktree (and every `git bisect` step that
# runs this), so absence is a skip, not an error.
if [ ! -d "$root/projects" ]; then
  echo "no $root/projects — skipping nested-repo hooks (root-only checkout or worktree)"
  exit 0
fi

# ------------------------------------------------------------------
# repo discovery
#
# This used to be `for candidate in "$root"/projects/*/*`, which hardcodes the assumption that
# a project's repository IS `projects/<group>/<name>`. That is only the common case. A project
# whose repos sit one level deeper — `projects/<group>/<name>/app/.git` and
# `projects/<group>/<name>/server/.git`, with `<name>` itself an ordinary directory — matched
# the glob at the `<name>` level, failed the `.git` test, and was skipped in silence. There was
# no output saying so: `found` counted only what the glob caught, so the installer reported
# success while two repos with live remotes had no push gate at all. The operator hit exactly
# that and decommissioned the project rather than the assumption.
#
# So repos are DISCOVERED by walking, not addressed by depth. The walk is bounded on four
# sides, because an unbounded walk over projects/ is a walk over every node_modules in the
# monorepo:
#   · MAX_DEPTH below projects/ — 4, so `<group>/<name>/<sub>/<sub2>` is reachable while a
#     deeply vendored tree is not.
#   · a discovered repo is a LEAF. Nothing descends into one, which is what keeps the walk off
#     `.git/` internals, off submodules, and off any repository vendored inside a project —
#     none of which are this monorepo's projects, and all of which would be surprising places
#     to find a gate installed.
#   · SKIP_DIRS: directories a project repo is never the child of. Dotted names go too, which
#     is what keeps `.claude/worktrees/` out — a worktree shares its parent's hooks directory,
#     so installing "into" one writes to a repo already covered.
#   · gitignore, asked of the nearest enclosing repository. Its one trap is the monorepo root:
#     `/projects/` is .gitignore:3 up there, so the root repo answers "ignored" for every
#     candidate under projects/ and honouring that verdict prunes the entire subtree — 6 repos
#     to 0. Measured. So the root's verdict is discarded and every other repo's is honoured.
# ------------------------------------------------------------------

MAX_DEPTH=4

skip_dir() {
  case "$1" in
    .*) return 0 ;;                                   # .git, .github, .claude/worktrees, …
    node_modules|vendor|Pods|target|__pycache__) return 0 ;;
    dist|build|out|coverage|html) return 0 ;;         # build output; `html` is docs-gen's
    *) return 1 ;;
  esac
}

# True when the nearest enclosing repository ignores this path. See the root-repo trap above.
path_is_ignored() {
  ignore_parent=$(dirname "$1")
  ignore_top=$(git -C "$ignore_parent" rev-parse --show-toplevel 2>/dev/null) || return 1
  [ "$ignore_top" = "$root" ] && return 1
  git -C "$ignore_parent" check-ignore -q "$1" 2>/dev/null
}

repos=""
discover() {
  discover_dir=$1
  discover_depth=$2
  [ "$discover_depth" -le "$MAX_DEPTH" ] || return 0
  for entry in "$discover_dir"/*; do
    [ -d "$entry" ] || continue
    # A symlinked directory is some other tree reached under a second name; following one
    # invites a cycle that only MAX_DEPTH would stop, and installs the same repo twice.
    [ -L "$entry" ] && continue
    skip_dir "${entry##*/}" && continue
    path_is_ignored "$entry" && continue
    if [ -e "$entry/.git" ]; then
      repos="$repos$entry
"
      continue
    fi
    discover "$entry" $((discover_depth + 1))
  done
}

discover "$root/projects" 1

found=0
while IFS= read -r candidate; do
  [ -n "$candidate" ] || continue
  found=$((found + 1))
  install_hook "$candidate" pre-commit "$nested_body"
  # The nested repos are the ones with live GitHub remotes — the root repo has none — so
  # this is the arm that actually matters for the push gate.
  install_hook "$candidate" pre-push   "$push_body"
done <<EOF
$repos
EOF

if [ "$found" -eq 0 ]; then
  echo "no nested git repositories under $root/projects"
fi

# The skips are REPORTED, which the glob version never did — that silence IS the bug this
# replaced. A project directory holding no repository at all is fine (northsoil-hr is one);
# a project holding a repository the walk could not REACH is the same failure again, one
# bound further out, so the two are told apart rather than both printed as "nothing to do".
# The second probe is a `find`, deliberately: it is not bound by MAX_DEPTH or SKIP_DIRS, so
# it can see precisely what the walk cannot, and it runs only for the handful of project
# directories the walk came back empty from. Depth 2 only — that is the level at which "a
# project" is a meaningful noun.
for candidate in "$root"/projects/*/*; do
  [ -d "$candidate" ] || continue
  [ -e "$candidate/.git" ] && continue
  case "$repos" in
    *"$candidate/"*) continue ;;   # its repos live deeper; already installed above
  esac
  unreached=$(find "$candidate" -maxdepth 6 -name .git -not -path '*/node_modules/*' -print 2>/dev/null | head -1)
  if [ -n "$unreached" ]; then
    echo "WARNING: ${candidate#"$root"/} holds a git repository this walk did not reach:" >&2
    echo "         ${unreached%/.git}" >&2
    echo "         It is deeper than MAX_DEPTH=$MAX_DEPTH below projects/, or under a skipped" >&2
    echo "         directory. It has NO pre-push gate. Move it up, or widen the bound." >&2
  else
    echo "note: ${candidate#"$root"/} contains no git repository — nothing to install into"
  fi
done
